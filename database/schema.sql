-- Extensión para generación de funciones estadísticas (opcional en PostgreSQL)
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

-- -------------------------------------------------------------------------
-- 1. Catálogo de Roles y Permisos (Módulo A: Usuarios y Roles)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rol (
    id_rol SMALLSERIAL PRIMARY KEY,
    nombre_rol VARCHAR(40) NOT NULL UNIQUE,
    permisos JSONB DEFAULT '[]'::jsonb NOT NULL,
    es_inicial BOOLEAN DEFAULT FALSE NOT NULL,
    codigo_rol VARCHAR(20) UNIQUE,
    descripcion VARCHAR(250)
);

-- -------------------------------------------------------------------------
-- 2. Usuarios del Sistema (Personal Clínico y Administrativo)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    documento_identidad VARCHAR(20) NOT NULL UNIQUE,
    correo VARCHAR(150) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    contrasena_hash VARCHAR(255) NOT NULL,
    estado BOOLEAN DEFAULT TRUE NOT NULL,
    firma_base64 TEXT
);

-- -------------------------------------------------------------------------
-- 3. Asignación N:M de Usuarios y Roles
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuario_rol (
    id_usuario INTEGER NOT NULL CONSTRAINT fk_usuario_rol_usuario REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    id_rol SMALLINT NOT NULL CONSTRAINT fk_usuario_rol_rol REFERENCES public.rol(id_rol) ON UPDATE CASCADE ON DELETE RESTRICT,
    estado BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_usuario_rol PRIMARY KEY (id_usuario, id_rol)
);

-- -------------------------------------------------------------------------
-- 4. Plantillas de Consentimiento Informado (Módulo D: Consentimientos)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.plantilla_consentimiento (
    id_consentimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    version SMALLINT DEFAULT 1 NOT NULL,
    estado BOOLEAN DEFAULT TRUE NOT NULL,
    texto_plantilla TEXT DEFAULT ''::text NOT NULL,
    id_usuario_modificador INTEGER CONSTRAINT fk_plantilla_cons_usuario REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- -------------------------------------------------------------------------
-- 5. Pacientes (Módulo C: Expediente Clínico)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.paciente (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    documento_identidad VARCHAR(20) NOT NULL UNIQUE,
    correo VARCHAR(150),
    telefono VARCHAR(20),
    fecha_nacimiento DATE NOT NULL,
    sexo VARCHAR(10)
);

-- -------------------------------------------------------------------------
-- 6. Bloques de Horario de Agenda (Módulo B: Agendamiento)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bloques_horario (
    inicio TIMESTAMP NOT NULL PRIMARY KEY,
    final TIMESTAMP NOT NULL,
    estado BOOLEAN DEFAULT TRUE NOT NULL,
    ocupacion BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT chk_rango_horario CHECK (final > inicio)
);

-- -------------------------------------------------------------------------
-- 7. Solicitudes de Cita Web (Portal Público de Pacientes)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.solicitud_cita (
    id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_solicitante VARCHAR(150) NOT NULL,
    documento_solicitante VARCHAR(20) NOT NULL,
    correo_solicitante VARCHAR(150) NOT NULL,
    bloque_solicitado TIMESTAMP NOT NULL CONSTRAINT fk_solicitud_bloque REFERENCES public.bloques_horario(inicio) ON UPDATE CASCADE ON DELETE RESTRICT,
    descripcion VARCHAR(500),
    estado BOOLEAN DEFAULT TRUE NOT NULL,
    telefono_solicitante VARCHAR(20),
    fecha_nacimiento DATE,
    sexo VARCHAR(10),
    fecha_solicitud TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- -------------------------------------------------------------------------
-- 8. Historial de Gestión de Solicitudes (Aprobaciones / Rechazos)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.historial_solicitud (
    id_cambio_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud INTEGER NOT NULL CONSTRAINT fk_hist_solicitud REFERENCES public.solicitud_cita(id_solicitud) ON UPDATE CASCADE ON DELETE CASCADE,
    id_usuario_gestor INTEGER NOT NULL CONSTRAINT fk_hist_solicitud_usuario REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_historial TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reporte VARCHAR(1000),
    motivo VARCHAR(500)
);

-- -------------------------------------------------------------------------
-- 9. Citas Odontológicas Programadas
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cita (
    id_cita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(50) NOT NULL,
    descripcion VARCHAR(500),
    id_paciente INTEGER NOT NULL CONSTRAINT fk_cita_paciente REFERENCES public.paciente(id_paciente) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_usuario INTEGER NOT NULL CONSTRAINT fk_cita_usuario REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    estado VARCHAR(20) NOT NULL
);

-- -------------------------------------------------------------------------
-- 10. Relación Bloques y Citas (Asociación N:M)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bloques_citas (
    id_bloque TIMESTAMP NOT NULL CONSTRAINT fk_bloques_citas_horario REFERENCES public.bloques_horario(inicio) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_cita INTEGER NOT NULL CONSTRAINT fk_bloques_citas_cita REFERENCES public.cita(id_cita) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT pk_bloques_citas PRIMARY KEY (id_bloque, id_cita)
);

-- -------------------------------------------------------------------------
-- 11. Historial de Citas (Trazabilidad y Estados)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.historial_cita (
    id_cambio_cita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita INTEGER NOT NULL CONSTRAINT fk_hist_cita REFERENCES public.cita(id_cita) ON UPDATE CASCADE ON DELETE CASCADE,
    id_usuario_gestor INTEGER NOT NULL CONSTRAINT fk_hist_cita_usuario REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_historial TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reporte VARCHAR(1000),
    motivo VARCHAR(500)
);

-- -------------------------------------------------------------------------
-- 12. Consentimientos Informados Firmados
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.consentimiento_firmado (
    id_consentimiento_firmado INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_consentimiento_firmado_id PRIMARY KEY,
    id_consentimiento INTEGER NOT NULL CONSTRAINT fk_cons_firmado_plantilla REFERENCES public.plantilla_consentimiento(id_consentimiento) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_paciente INTEGER NOT NULL CONSTRAINT fk_cons_firmado_paciente REFERENCES public.paciente(id_paciente) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version_plantilla SMALLINT DEFAULT 1 NOT NULL,
    texto_firmado TEXT DEFAULT ''::text NOT NULL,
    firma_base64 TEXT DEFAULT ''::text NOT NULL,
    firma_por_acudiente BOOLEAN DEFAULT FALSE NOT NULL,
    nombre_documento_acudiente VARCHAR(200),
    id_usuario_diligencio INTEGER CONSTRAINT fk_cons_firmado_usuario_diligencio REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_acudiente_consentimiento CHECK (
        (NOT firma_por_acudiente) OR
        ((nombre_documento_acudiente IS NOT NULL) AND (btrim((nombre_documento_acudiente)::text) <> ''::text))
    )
);

-- -------------------------------------------------------------------------
-- 13. Historias Clínicas (Expediente Base)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.historia_clinica (
    id_historia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL UNIQUE CONSTRAINT fk_historia_paciente REFERENCES public.paciente(id_paciente) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- -------------------------------------------------------------------------
-- 14. Evoluciones Clínicas y Odontogramas
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.evolucion (
    id_evolucion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_historia INTEGER NOT NULL CONSTRAINT fk_evolucion_historia REFERENCES public.historia_clinica(id_historia) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id_cita INTEGER NOT NULL CONSTRAINT uq_evolucion_cita UNIQUE CONSTRAINT fk_evolucion_cita REFERENCES public.cita(id_cita) ON UPDATE CASCADE ON DELETE RESTRICT,
    motivo_consulta VARCHAR(250) NOT NULL,
    enfermedad_actual VARCHAR(1000) DEFAULT 'N/A'::character varying,
    antecedentes_clinicos JSONB DEFAULT '{}'::jsonb,
    habitos_higiene JSONB DEFAULT '{}'::jsonb,
    examen_estomatognatico JSONB DEFAULT '{}'::jsonb,
    examen_fisico_observaciones TEXT,
    odontograma JSONB DEFAULT '{}'::jsonb,
    procedimiento_realizado TEXT,
    diagnostico_generado TEXT,
    acciones_a_realizar TEXT,
    hallazgos_observaciones TEXT,
    plan_manejo JSONB DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_evolucion_historia_fecha ON public.evolucion (id_historia ASC, fecha DESC);

-- -------------------------------------------------------------------------
-- 15. Auditoría de Modificaciones de Historias Clínicas (DEF-14 / Res. 1995/1999)
-- -------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.auditoria_historia_clinica (
    id_auditoria SERIAL PRIMARY KEY,
    id_evolucion INTEGER REFERENCES public.evolucion(id_evolucion) ON UPDATE CASCADE ON DELETE CASCADE,
    id_usuario_modificador INTEGER REFERENCES public.usuario(id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    campo_modificado VARCHAR(100) NOT NULL,
    valor_anterior JSONB NOT NULL,
    valor_nuevo JSONB NOT NULL,
    fecha_modificacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
