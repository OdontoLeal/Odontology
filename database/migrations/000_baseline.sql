-- 000_baseline.sql
-- Esquema base de OdontoLeal tal como estaba en producción antes de la
-- ERS v1.3 (fuente: "DDL actual.txt", 04/11/2026).
-- Es idempotente: en una BD que ya tiene estas tablas no cambia nada.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.rol
(
    id_rol      smallserial
        primary key,
    nombre_rol  varchar(40)                 not null
        unique,
    permisos    jsonb   default '[]'::jsonb not null,
    es_inicial  boolean default false       not null,
    codigo_rol  varchar(20)
        unique,
    descripcion varchar(250)
);

CREATE TABLE IF NOT EXISTS public.usuario
(
    id_usuario          integer generated by default as identity
        primary key,
    nombre_completo     varchar(150)         not null,
    documento_identidad varchar(20)          not null
        unique,
    correo              varchar(150)         not null
        unique,
    telefono            varchar(20),
    contrasena_hash     varchar(255)         not null,
    estado              boolean default true not null,
    firma_base64        text
);

CREATE TABLE IF NOT EXISTS public.usuario_rol
(
    id_usuario integer              not null
        constraint fk_usuario_rol_usuario
            references usuario
            on update cascade on delete cascade,
    id_rol     smallint             not null
        constraint fk_usuario_rol_rol
            references rol
            on update cascade on delete restrict,
    estado     boolean default true not null,
    constraint pk_usuario_rol
        primary key (id_usuario, id_rol)
);

CREATE TABLE IF NOT EXISTS public.plantilla_consentimiento
(
    id_consentimiento      integer generated by default as identity
        primary key,
    nombre                 varchar(150)                        not null
        unique,
    version                smallint  default 1                 not null,
    estado                 boolean   default true              not null,
    texto_plantilla        text      default ''::text          not null,
    id_usuario_modificador integer
        constraint fk_plantilla_cons_usuario
            references usuario
            on update cascade on delete restrict,
    fecha_modificacion     timestamp default CURRENT_TIMESTAMP not null
);

CREATE TABLE IF NOT EXISTS public.paciente
(
    id_paciente         integer generated by default as identity
        primary key,
    nombre_completo     varchar(150) not null,
    documento_identidad varchar(20)  not null
        unique,
    correo              varchar(150),
    telefono            varchar(20),
    fecha_nacimiento    date         not null,
    sexo                varchar(10)
);

CREATE TABLE IF NOT EXISTS public.bloques_horario
(
    inicio    timestamp             not null
        primary key,
    final     timestamp             not null,
    estado    boolean default true  not null,
    ocupacion boolean default false not null,
    constraint chk_rango_horario
        check (final > inicio)
);

CREATE TABLE IF NOT EXISTS public.solicitud_cita
(
    id_solicitud          integer generated by default as identity
        primary key,
    nombre_solicitante    varchar(150)           not null,
    documento_solicitante varchar(20)            not null,
    correo_solicitante    varchar(150)           not null,
    bloque_solicitado     timestamp              not null
        constraint fk_solicitud_bloque
            references bloques_horario
            on update cascade on delete restrict,
    descripcion           varchar(500),
    estado                boolean   default true not null,
    telefono_solicitante  varchar(20),
    fecha_nacimiento      date,
    sexo                  varchar(10),
    fecha_solicitud       timestamp default CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.historial_solicitud
(
    id_cambio_solicitud integer generated by default as identity
        primary key,
    id_solicitud        integer                             not null
        constraint fk_hist_solicitud
            references solicitud_cita
            on update cascade on delete cascade,
    id_usuario_gestor   integer                             not null
        constraint fk_hist_solicitud_usuario
            references usuario
            on update cascade on delete restrict,
    fecha_historial     timestamp default CURRENT_TIMESTAMP not null,
    reporte             varchar(1000),
    motivo              varchar(500)
);

CREATE TABLE IF NOT EXISTS public.cita
(
    id_cita     integer generated by default as identity
        primary key,
    titulo      varchar(50) not null,
    descripcion varchar(500),
    id_paciente integer     not null
        constraint fk_cita_paciente
            references paciente
            on update cascade on delete restrict,
    id_usuario  integer     not null
        constraint fk_cita_usuario
            references usuario
            on update cascade on delete restrict,
    estado      varchar(20) not null
);

CREATE TABLE IF NOT EXISTS public.bloques_citas
(
    id_bloque timestamp not null
        constraint fk_bloques_citas_horario
            references bloques_horario
            on update cascade on delete restrict,
    id_cita   integer   not null
        constraint fk_bloques_citas_cita
            references cita
            on update cascade on delete cascade,
    constraint pk_bloques_citas
        primary key (id_bloque, id_cita)
);

CREATE TABLE IF NOT EXISTS public.historial_cita
(
    id_cambio_cita    integer generated by default as identity
        primary key,
    id_cita           integer                             not null
        constraint fk_hist_cita
            references cita
            on update cascade on delete cascade,
    id_usuario_gestor integer                             not null
        constraint fk_hist_cita_usuario
            references usuario
            on update cascade on delete restrict,
    fecha_historial   timestamp default CURRENT_TIMESTAMP not null,
    reporte           varchar(1000),
    motivo            varchar(500)
);

CREATE TABLE IF NOT EXISTS public.consentimiento_firmado
(
    id_consentimiento          integer                             not null
        constraint fk_cons_firmado_plantilla
            references plantilla_consentimiento
            on update cascade on delete restrict,
    id_paciente                integer                             not null
        constraint fk_cons_firmado_paciente
            references paciente
            on update cascade on delete restrict,
    fecha                      timestamp default CURRENT_TIMESTAMP not null,
    id_consentimiento_firmado  integer generated by default as identity
        constraint pk_consentimiento_firmado_id
            primary key,
    version_plantilla          smallint  default 1                 not null,
    texto_firmado              text      default ''::text          not null,
    firma_base64               text      default ''::text          not null,
    firma_por_acudiente        boolean   default false             not null,
    nombre_documento_acudiente varchar(200),
    id_usuario_diligencio      integer
        constraint fk_cons_firmado_usuario_diligencio
            references usuario
            on update cascade on delete restrict,
    constraint chk_acudiente_consentimiento
        check ((NOT firma_por_acudiente) OR
               ((nombre_documento_acudiente IS NOT NULL) AND (btrim((nombre_documento_acudiente)::text) <> ''::text)))
);

CREATE TABLE IF NOT EXISTS public.historia_clinica
(
    id_historia    integer generated by default as identity
        primary key,
    id_paciente    integer                             not null
        unique
        constraint fk_historia_paciente
            references paciente
            on update cascade on delete restrict,
    fecha_creacion timestamp default CURRENT_TIMESTAMP not null
);

CREATE TABLE IF NOT EXISTS public.evolucion
(
    id_evolucion                integer generated by default as identity
        primary key,
    id_historia                 integer                                 not null
        constraint fk_evolucion_historia
            references historia_clinica
            on update cascade on delete restrict,
    fecha                       timestamp     default CURRENT_TIMESTAMP not null,
    id_cita                     integer                                 not null
        constraint uq_evolucion_cita
            unique
        constraint fk_evolucion_cita
            references cita
            on update cascade on delete restrict,
    motivo_consulta             varchar(250)                            not null,
    enfermedad_actual           varchar(1000) default 'N/A'::character varying,
    antecedentes_clinicos       jsonb         default '{}'::jsonb,
    habitos_higiene             jsonb         default '{}'::jsonb,
    examen_estomatognatico      jsonb         default '{}'::jsonb,
    examen_fisico_observaciones text,
    odontograma                 jsonb         default '{}'::jsonb,
    procedimiento_realizado     text,
    diagnostico_generado        text,
    acciones_a_realizar         text,
    hallazgos_observaciones     text,
    plan_manejo                 jsonb         default '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_evolucion_historia_fecha
    on evolucion (id_historia asc, fecha desc);

CREATE TABLE IF NOT EXISTS public.token_recuperacion
(
    token      varchar(255)          not null
        primary key,
    id_usuario integer               not null,
    correo     varchar(150)          not null,
    creado_en  timestamp             not null,
    expira_en  timestamp             not null,
    usado      boolean default false not null,
    invalidado boolean default false not null
);
